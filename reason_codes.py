    SUPPLIER_SUSPENDED = "SUPPLIER_SUSPENDED"
    PRODUCT_UNKNOWN = "PRODUCT_UNKNOWN"
    PRODUCT_INACTIVE = "PRODUCT_INACTIVE"
    OFFER_UNKNOWN = "OFFER_UNKNOWN"
    OFFER_PRODUCT_MISMATCH = "OFFER_PRODUCT_MISMATCH"
    OFFER_SUPPLIER_MISMATCH = "OFFER_SUPPLIER_MISMATCH"
    INVALID_QUANTITY = "INVALID_QUANTITY"
    BELOW_MINIMUM_ORDER_QUANTITY = "BELOW_MINIMUM_ORDER_QUANTITY"
    INVALID_ORDER_MULTIPLE = "INVALID_ORDER_MULTIPLE"
    SUPPLIER_STOCK_INSUFFICIENT = "SUPPLIER_STOCK_INSUFFICIENT"
    CURRENCY_NOT_ALLOWED = "CURRENCY_NOT_ALLOWED"
    OFFER_CURRENCY_MISMATCH = "OFFER_CURRENCY_MISMATCH"
    UNIT_PRICE_MISMATCH = "UNIT_PRICE_MISMATCH"
    TOTAL_MISMATCH = "TOTAL_MISMATCH"
