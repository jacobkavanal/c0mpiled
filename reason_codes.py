"""Stable outcomes and reason codes for the CTRL controller.

Member ORDER of ReasonCode is part of the contract: reason codes in a Decision
are sorted by this order so results stay deterministic.
"""
from __future__ import annotations

from enum import Enum


class Outcome(str, Enum):
    ALLOW = "ALLOW"
    ESCALATE = "ESCALATE"
    BLOCK = "BLOCK"
    STOP = "STOP"


# Higher number wins: STOP > BLOCK > ESCALATE > ALLOW
OUTCOME_PRECEDENCE = {
    Outcome.ALLOW: 0,
    Outcome.ESCALATE: 1,
    Outcome.BLOCK: 2,
    Outcome.STOP: 3,
}


class ReasonCode(str, Enum):
    # ---- STOP ----
    RETRY_LIMIT_REACHED = "RETRY_LIMIT_REACHED"
    REPEATED_DENIED_ACTION = "REPEATED_DENIED_ACTION"

    # ---- BLOCK ----
